// Functions: each a `FunctionCall` of the basic catalog's function, its unset optional arguments left out.

const call = (name: string, args: Readonly<Record<string, unknown>>, catalogId?: string): FunctionCall =>
  new FunctionCall(name, Object.fromEntries(Object.entries(args).filter(([, v]) => v !== undefined)), { catalogId })

interface CallOptions {
  readonly catalogId?: string | undefined
}

/** Checks that the value is not null, undefined, or empty. */
export const Required = (a: { readonly value: unknown } & CallOptions): FunctionCall => call("required", { value: a.value }, a.catalogId)
/** Checks that the value matches a regular expression string. */
export const Regex = (a: { readonly value: DynamicString; readonly pattern: string } & CallOptions): FunctionCall =>
  call("regex", { value: a.value, pattern: a.pattern }, a.catalogId)
/** Checks string length constraints. */
export const Length = (a: { readonly value: DynamicString; readonly min?: number; readonly max?: number } & CallOptions): FunctionCall =>
  call("length", { value: a.value, min: a.min, max: a.max }, a.catalogId)
/** Checks numeric range constraints. */
export const Numeric = (a: { readonly value: DynamicNumber; readonly min?: number; readonly max?: number } & CallOptions): FunctionCall =>
  call("numeric", { value: a.value, min: a.min, max: a.max }, a.catalogId)
/** Checks that the value is a valid email address. */
export const Email = (a: { readonly value: DynamicString } & CallOptions): FunctionCall => call("email", { value: a.value }, a.catalogId)
/** Interpolates `${expression}`s (data paths and function calls) into a string. */
export const FormatString = (a: { readonly value: DynamicString } & CallOptions): FunctionCall => call("formatString", { value: a.value }, a.catalogId)
/** Formats a number with the given grouping and decimal precision. */
export const FormatNumber = (
  a: { readonly value: DynamicNumber; readonly decimals?: DynamicNumber; readonly grouping?: DynamicBoolean } & CallOptions,
): FunctionCall => call("formatNumber", { value: a.value, decimals: a.decimals, grouping: a.grouping }, a.catalogId)
/** Formats a number as a currency string. */
export const FormatCurrency = (
  a: { readonly value: DynamicNumber; readonly currency: DynamicString; readonly decimals?: DynamicNumber; readonly grouping?: DynamicBoolean } & CallOptions,
): FunctionCall => call("formatCurrency", { value: a.value, currency: a.currency, decimals: a.decimals, grouping: a.grouping }, a.catalogId)
/** Formats a timestamp into a string using a pattern. */
export const FormatDate = (a: { readonly value: unknown; readonly format: DynamicString } & CallOptions): FunctionCall =>
  call("formatDate", { value: a.value, format: a.format }, a.catalogId)
/** Picks a localized string by the CLDR plural category of the count; `other` is the fallback. */
export const Pluralize = (
  a: {
    readonly value: DynamicNumber
    readonly zero?: DynamicString
    readonly one?: DynamicString
    readonly two?: DynamicString
    readonly few?: DynamicString
    readonly many?: DynamicString
    readonly other: DynamicString
  } & CallOptions,
): FunctionCall => call("pluralize", { value: a.value, other: a.other, zero: a.zero, one: a.one, two: a.two, few: a.few, many: a.many }, a.catalogId)
/** Opens the URL in a browser or handler (requires user activation). */
export const OpenUrl = (a: { readonly url: DynamicString } & CallOptions): FunctionCall => call("openUrl", { url: a.url }, a.catalogId)
/** Logical AND of a list of booleans. */
export const And = (a: { readonly values: ReadonlyArray<DynamicBoolean> } & CallOptions): FunctionCall => call("and", { values: a.values }, a.catalogId)
/** Logical OR of a list of booleans. */
export const Or = (a: { readonly values: ReadonlyArray<DynamicBoolean> } & CallOptions): FunctionCall => call("or", { values: a.values }, a.catalogId)
/** Logical NOT of a boolean. */
export const Not = (a: { readonly value: DynamicBoolean } & CallOptions): FunctionCall => call("not", { value: a.value }, a.catalogId)
