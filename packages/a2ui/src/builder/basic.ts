// Item models: plain objects, written as they are.

/** An icon drawn from an SVG path. */
export interface IconNameSvgPath {
  readonly svgPath: DynamicString
}
/** A tab: its title and its content. */
export interface TabItem {
  readonly title: DynamicString
  readonly child: Child
}
/** An option of a `ChoicePicker`. */
export interface ChoicePickerOption {
  readonly label: DynamicString
  readonly value: string
}

/** The `@checks` of an input component. */
interface Checkable {
  readonly checks?: ReadonlyArray<CheckRule> | undefined
}
interface Weighted {
  readonly weight?: number | undefined
}
const CHECKS = { checks: "@checks" } as const

